    def rx_fav_delete(self, rows):
        idx = sorted({int(r) for r in rows if str(r).isdigit() and int(r) < len(self.rx_favs)}, reverse=True)
        gone = [(i, self.rx_favs[i]) for i in idx]
        if not gone:
            return
        for i, _f in gone:
            del self.rx_favs[i]
        label = f"{len(gone)} favorite{'s' if len(gone) != 1 else ''}"

        def restore():
            for i, f in sorted(gone, key=lambda g: g[0]):
                self.rx_favs.insert(min(i, len(self.rx_favs)), f)
            self.rx_fav_changed()
        self.push_undo("regex", label, restore)
        self.rx_fav_changed()
        self._say(f"Removed {label}. Ctrl+Z (or Undo) puts them back.", 8)

    def _rx_unique(self, kind, name):
        taken = {f["name"] for f in self.rx_favs if f["kind"] == kind}
        out, n = name, 2
        while out in taken:
            out, n = f"{name} ({n})", n + 1
        return out

