def _blank():
    return {"want": {}, "avoid": [], "all": False, "opts": {}}


def _rng(m):
    if m.get("min") is None or "#" not in m["line"]:
        return ""
    a, b = m["min"], m["max"]
    return f"{a:g}" if a == b else f"{a:g}-{b:g}"


