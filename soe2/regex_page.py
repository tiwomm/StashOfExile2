def _val_text(cur):
    return "" if cur is None else f"{cur:g}" if isinstance(cur, (int, float)) else str(cur)


def _rng(m):
    if m.get("min") is None or "#" not in m["line"]:
        return ""
    a, b = m["min"], m["max"]
    return f"{a:g}" if a == b else f"{a:g}-{b:g}"


