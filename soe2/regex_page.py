    def rx_key_press(self, i):
        """Regex key i was pressed in game: its favorite goes on the clipboard (Ctrl+V in the stash search)."""
        keys = self.rx_keys()
        if i >= len(keys):
            return None
        name, s = self.rx_ref_search(keys[i]["fav"])
