    def rx_fav_rename(self):
        f = (self._rx_fav_sel() or [None])[0]
        if not f or not self._rx_one_mine():
            return self._say("Select a favorite first.", 5)
        name = simpledialog.askstring("Rename", "New name:", initialvalue=f["name"], parent=self.root)
        if not name or not name.strip() or name.strip() == f["name"]:
            return
        old = f"preset:{f['kind']}:{f['name']}"
        f["name"] = self._rx_unique(f["kind"], name.strip())
        new = f"preset:{f['kind']}:{f['name']}"
        for k in self.rx_keys():                                   # (its Regex key follows it)
            if k["fav"] == old:
                k["fav"] = new
        save_json("settings.json", SETTINGS)
        self.rx_fav_changed()

    def rx_fav_delete(self, rows):
        idx = sorted({self.rx_rows[r]["_i"] for r in rows if r in getattr(self, "rx_rows", {})
                      and self.rx_rows[r]["_origin"] == "mine"}, reverse=True)
        gone = [(i, self.rx_favs[i]) for i in idx if i < len(self.rx_favs)]
        if not gone:
            return
        for i, _f in gone:
            del self.rx_favs[i]
        label = f"{len(gone)} favorite{'s' if len(gone) != 1 else ''}"

        def restore():
            for i, f in sorted(gone, key=lambda g: g[0]):
                self.rx_favs.insert(min(i, len(self.rx_favs)), f)
            self.rx_fav_changed()
        self.push_undo("regex", label, restore)
        self.rx_fav_changed()
        self._say(f"Removed {label}. Ctrl+Z (or Undo) puts them back.", 8)

    def _rx_unique(self, kind, name):
        taken = {f["name"] for f in self.rx_favs if f["kind"] == kind}
        out, n = name, 2
        while out in taken:
            out, n = f"{name} ({n})", n + 1
        return out

