        self.ignore_clip(s)
        self.own_clip = s
        self.root.clipboard_clear()
        self.root.clipboard_append(s)
        self.toast.show("Stash search copied", [f"{label} ({len(s)} characters)",
                                                "In your stash: Ctrl+F, then Ctrl+V."], C["accent"], 4)

