    def rx_select_valuable(self):
        """Add every mod the Mod book rates High to "I want" (Match: Any - one valuable mod is enough)."""
        st = self._rx()
        picked = [mid for mid, (imp, _w) in getattr(self, "rx_worths", {}).items() if imp == "high"]
        for mid in picked:
            st["want"].setdefault(mid, None)
            if mid in st["avoid"]:
                st["avoid"].remove(mid)
        st["all"] = False
        self.rx_paint_all()
        self.rx_update()
        self.rx_save()

