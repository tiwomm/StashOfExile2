    def rx_filter(self):
        q = self.rx_q.get().strip().lower() if hasattr(self, "rx_q") else ""
        only = bool(getattr(self, "rx_only_val", None) and self.rx_only_val.get())
        first = bool(getattr(self, "rx_val_first", None) and self.rx_val_first.get())
        worths = getattr(self, "rx_worths", {})
        rank = {"high": 0, "normal": 1, "ignore": 2}
        shown = 0
        slots = set()
        if self.rx_kind.get() == "gear":                     # 2.22.0: only the mods that roll on the picked slots
            slots = set(self._rx()["opts"].get("slots") or [])
            if slots & {"Helmet", "Gloves", "Boots", "Body Armour"}:
                slots.add("Armour")
        for side, L in self.rx_lists.items():
            tv = L["tree"]
            rows = list(L["rows"].items())
            if first:                                        # ★ mods at the top (2.0 beta 20)
                rows.sort(key=lambda kv: rank.get(worths.get(kv[0], ("normal",))[0], 1))
            keep = []
            for mid, r in rows:
                m = r["mod"]
                if q and q not in m["text"] and q not in " ".join(m["tags"]).lower():
                    continue
                if only and worths.get(mid, ("normal",))[0] != "high":
                    continue
                if slots and not slots & set(m["tags"]):
                    continue
                keep.append(mid)
            if tuple(keep) != tv.get_children():
                tv.detach(*L["rows"])
                for i, mid in enumerate(keep):
                    tv.move(mid, "", i)
            if side == "want":
                shown = len(keep)
        self._rx_edit_place()
        total = len(R.mods(self.rx_kind.get()))
        err = R.load().get("error")
        self.rx_info.config(text=err or (f"{shown} of {total} mods" if shown != total else f"{total} mods"),
                            fg=C["red"] if err else C["muted"])

