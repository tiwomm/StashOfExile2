    def rx_save_preset(self):
        kind = self.rx_kind.get()
        if not any((self._rx().get("want"), self._rx().get("avoid"), any(self._rx().get("opts", {}).values()))):
            return self._say("Pick some mods or options first, then add the search to your Favorites.", 6)
        name = simpledialog.askstring("Add to Favorites", f"Name for this {KIND_NAMES[kind][:-1].lower()} search:",
                                      parent=self.root, initialvalue=self.rx_preset.get())
        if not name or not name.strip():
            return
        name = name.strip()
        same = next((f for f in self.rx_favs if f["kind"] == kind and f["name"] == name), None)
        if same:                                          # the same name again: update it
            same["state"], same["added"] = copy.deepcopy(self._rx()), time.time()
        else:
            self.rx_favs.append({"name": name, "kind": kind, "state": copy.deepcopy(self._rx()), "added": time.time()})
        self.rx_preset.set(name)
        self.rx_fav_changed()
        self._say(f"Added \"{name}\" to your Favorites.", 6)

    def rx_load_preset(self):
        """(Older callers: open the favorite named in rx_preset.)"""
        f = next((f for f in self.rx_favs if f["kind"] == self.rx_kind.get() and f["name"] == self.rx_preset.get()), None)
        if f:
            name = f["name"]
            self.rx_state[f["kind"]] = copy.deepcopy(f["state"])
            self.rx_kind_changed()
            self.rx_preset.set(name)

