    def rx_read_opts(self):
        st, v = self._rx(), self.rx_vars
        o = {}
        for key, var in v.items():
            if key.startswith(("rar:", "type:", "size:", "slot:")):
                if var.get():
                    group, val = key.split(":", 1)
                    o.setdefault({"rar": "rarity", "type": "types", "size": "sizes", "slot": "slots"}[group],
                                 []).append(val)
            elif key in ("round10",):
                o[key] = bool(var.get())
            elif key in ("cor_only", "cor_not"):
                continue
            else:
                txt = var.get().strip()
                if txt.isdigit():
                    o[key] = int(txt)
        only, not_ = v.get("cor_only"), v.get("cor_not")
        if only is not None:
            if only.get() and not not_.get():
                o["corrupted"] = "only"
            elif not_.get() and not only.get():
                o["corrupted"] = "not"
        st["opts"] = o

    def _rx_cancel_opts_job(self):
        if self._rx_opts_job is not None:
            self.root.after_cancel(self._rx_opts_job)
            self._rx_opts_job = None

    def rx_schedule_opts(self):
        self._rx_cancel_opts_job()
        self._rx_opts_job = self.root.after(150, self.rx_opts_ready)

    def rx_opts_ready(self):
        self._rx_opts_job = None
        self.rx_commit_opts()

    def rx_commit_opts(self):
        self._rx_cancel_opts_job()
        if self.rx_kind.get() == "gear":                   # 2.22.0: the slot boxes pick which mods are listed
            self.rx_filter()
        self.rx_update()
        self.rx_save()

    # ---------------- the two mod lists
    def rx_build_lists(self):
        """The two mod lists for the item type picked (2.26.4: filling a Treeview takes a few milliseconds, even for
        650 gear mods)."""
        self._rx_edit_close()
        kind = self.rx_kind.get()
        for side, L in self.rx_lists.items():
            tv = L["tree"]
            old = [i for i in L["rows"] if tv.exists(i)]
            if old:
                tv.delete(*old)                              # (the hidden ones too)
            rows = {}
            for m in R.mods(kind):
                where = [] if kind == "waystone" else [t for t in m["tags"] if t != "Any"]
                txt = m["text"]
                rows[m["id"]] = {"mod": m, "text": txt[:1].upper() + txt[1:], "where": ", ".join(where)}
                tv.insert("", "end", iid=m["id"], values=("", "", rows[m["id"]]["text"], rows[m["id"]]["where"]))
            L["rows"] = rows
            tv.yview_moveto(0)
        self.rx_refresh_values()

    # ---------------- what the Mod book says about each mod (2.0 beta 20)
    @staticmethod
    def rx_worth(m, kind="tablet"):
        """-> ("high" / "normal" / "ignore", why) for a regex mod, from the Mod book: your rules first, then what it
        learned from prices, shared rules and the built-in defaults - the same rule the price checker uses.
        2.6.0: waystone and relic mods use their own rules (Mod book > Waystone rules / Relic rules)."""
        from .mods import COMMUNITY_ACTIVE, impact_key, learned_info, norm, rule_key, RULES
        order = ["ignore", "normal", "high"]
        rated = []
        for line in m.get("lines") or [m["line"]]:
            k = rule_key(kind, norm(line))
            li = learned_info(k)
            why = ("your Mod Book rule" if k in RULES else "learned from prices" if li and li.get("tier") == "high" else
                   "shared rules" if k in COMMUNITY_ACTIVE else "built-in rule")
            rated.append((impact_key(k), why))
        return max(rated, key=lambda r: order.index(r[0])) if rated else ("normal", "")

