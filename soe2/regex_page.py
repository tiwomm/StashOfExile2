    def rx_paste_test(self, text=None):
        if text is None:
            text = read_clipboard_text()
            if not text:
                try:
                    text = self.root.clipboard_get()
                except tk.TclError:
                    text = ""
        if not text or not text.lstrip().startswith("Item Class:"):
            self.rx_test_out.config(text="The clipboard has no item: hover one in game, press Ctrl+C, then try again.", fg=C["red"])
            return
        self.rx_test_text = text
        self.rx_pick_btn.pack(side="right")
        self.rx_test()

    def rx_test(self):
        if not getattr(self, "rx_test_text", ""):
            return
        s, _ = self.rx_current()
        lines = [l.strip() for l in self.rx_test_text.replace("\r", "").split("\n") if l.strip()]
        name = next((l for l in lines[2:4] if not l.startswith("--")), "the item")
        if not s:
            self.rx_test_out.config(text=f"Copied: {name}. Select some mods or options first.", fg=C["muted"])
            return
        ok, rows = R.test(s, self.rx_test_text)
        miss = [("not " if neg else "") + f"\"{body[:30]}\"" for body, neg, good, _hit in rows if not good]
        self.rx_test_out.config(text=(f"✔ {name}: lights up with this search." if ok else
                                      f"✘ {name}: doesn't light up - fails on " + ", ".join(miss) + "."),
                                fg=C["green"] if ok else C["red"])

    def rx_tick_item(self):
        if not self.rx_test_text:
            return
        found = R.matching_mods(self.rx_kind.get(), self.rx_test_text)
        st = self._rx()
        for i in found:
            st["want"].setdefault(i, None)
            if i in st["avoid"]:
                st["avoid"].remove(i)
        for i in found:
            self.rx_paint(i)
        self.rx_update()
        self.rx_save()
        self._say(f"Selected the {len(found)} mod{'s' if len(found) != 1 else ''} this item has.", 6)
