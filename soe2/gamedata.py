"""The game-data library (1.38, Phase 2): every PoE 2 base type with its class, defence type and base group, every
modifier's trade-site stat, the pseudo totals, stackable currency names; plus reading any copied item's text.

gamedata.json is generated by tools/build_gamedata.py from Exiled Exchange 2's data (MIT license, see
THIRD_PARTY_NOTICES.txt). It ships inside the app and is copied into the data folder like tabs.txt (versioned)."""
import json
import os
import re
import threading

from .config import APP_DIR, P, RESOURCE_DIR, load_json, save_json

_lock = threading.Lock()
_data = None
_by_text = {}          # normalised mod wording -> [(stat, negate)]
_bases_by_len = []     # base names, longest first (to find a base inside a magic item's name)
_class_by_text = {}    # "body armours" -> class id
_fallback = [None]     # 1.40: the window plugs in a lookup on the trade site's own stat list (for lines not in gamedata)
LEARNED_FILE = "learned_stats.json"     # wordings learned that way, kept between sessions
# lines that describe the whole item, not a mod
FLAG_LINES = {"Corrupted": "corrupted", "Unidentified": "unidentified", "Mirrored": "mirrored", "Split": "split",
              "Fractured Item": "fractured", "Synthesised Item": "synthesised", "Sanctified": "sanctified",
              "Unmodifiable": "unmodifiable"}
SOURCES = ("fractured", "desecrated", "crafted")


def _find_file():
    for p in (P("gamedata.json"), os.path.join(RESOURCE_DIR, "gamedata.json"), os.path.join(APP_DIR, "gamedata.json")):
        if os.path.isfile(p):
            return p
    return None


def load():
    """The library, loaded once. Missing / broken file -> an empty library (callers check available())."""
    global _data
    with _lock:
        if _data is not None:
            return _data
        path = _find_file()
        try:
            with open(path, encoding="utf-8") as f:
                d = json.load(f)
        except Exception as e:
            d = {"classes": {}, "groups": {}, "bases": {}, "stats": [], "pseudo_rules": [], "currency": {},
                 "uniques": {}, "error": f"gamedata.json {'not found' if not path else 'could not be read'} ({e})"}
        for s in d["stats"]:
            for m in s.get("matchers", []):
                _by_text.setdefault(norm_mod(m["string"]), []).append((s, bool(m.get("negate"))))
        for key, e in (load_json(LEARNED_FILE, {}) or {}).items():     # learned from the trade site earlier
            if key not in _by_text:
                _by_text[key] = [({"ref": e["ref"], "trade": e["trade"], "better": 1, "learned": True}, bool(e.get("negate")))]
        _bases_by_len.extend(sorted(d["bases"], key=len, reverse=True))
        for cid, c in d["classes"].items():
            _class_by_text[c["name"].lower()] = cid
        _class_by_text.update({"life flasks": "flask", "mana flasks": "flask", "foci": "focus", "warstaves": "quarterstaff"})
        _data = d
        return d


def available():
    return bool(load()["bases"])


def info():
    d = load()
    return {"bases": len(d["bases"]), "groups": len(d["groups"]), "classes": len(d["classes"]), "stats": len(d["stats"]),
            "version": d.get("version"), "generated": d.get("generated"), "source": d.get("source", {}),
            "error": d.get("error")}


# ---------------------------------------------------------------- lookups
def base(name):
    return load()["bases"].get((name or "").strip())


def group(gid):
    return load()["groups"].get(gid)


def classes():
    return load()["classes"]


def groups():
    return load()["groups"]


def class_from_text(text):
    load()
    return _class_by_text.get((text or "").strip().lower())


def find_base(text):
    """The base type inside a name line: exact first, else the longest base name it contains (magic items carry
    affixes around the base: 'Sapphire Ring of the Whale')."""
    d = load()
    t = (text or "").strip()
    if t in d["bases"]:
        return t
    for b in _bases_by_len:
        if re.search(rf"(?<![A-Za-z']){re.escape(b)}(?![A-Za-z'])", t):
            return b
    return None


_MARKUP = re.compile(r"\[([^\]|]*\|)?([^\]]*)\]")
_RANGE = re.compile(r"\((-?\d+(?:\.\d+)?)[-–](-?\d+(?:\.\d+)?)\)")
_NUM = re.compile(r"[+-]?\d+(?:[.,]\d+)?")
_TAGS = re.compile(r"\s*\((implicit|rune|enchant|crafted|desecrated|fractured|augmented|unscalable value|sanctum)\)\s*$", re.I)


def norm_mod(text):
    """Mod wording with every number as '#', lower-case: '+52(40-59) to maximum Life' -> '# to maximum life'."""
    t = _MARKUP.sub(r"\2", text or "")
    t = _RANGE.sub("", t)
    while _TAGS.search(t):
        t = _TAGS.sub("", t)
    t = _NUM.sub("#", t)
    t = t.replace("+#", "#")
    return re.sub(r"\s+", " ", t).strip().lower()


def set_fallback(fn):
    """fn(line) -> {"ref", "trade": {group: [ids]}, "negate"} from the trade site's stat list, or None."""
    _fallback[0] = fn


def stat_for(text, learn=True):
    """-> (stat entry, negate) for a mod line, or (None, False). A wording gamedata doesn't know is looked up on the
    trade site's own stat list (if the window plugged that in) and remembered in learned_stats.json."""
    load()
    key = norm_mod(text)
    hits = _by_text.get(key)
    if hits:
        return hits[0]
    if learn and _fallback[0]:
        try:
            got = _fallback[0](text)
        except Exception:
            got = None
        if got and got.get("trade"):
            e = {"ref": got.get("ref") or key, "trade": got["trade"], "better": 1, "learned": True}
            _by_text[key] = [(e, bool(got.get("negate")))]
            with _lock:
                saved = load_json(LEARNED_FILE, {}) or {}
                saved[key] = {"ref": e["ref"], "trade": e["trade"], "negate": bool(got.get("negate"))}
                save_json(LEARNED_FILE, saved)
            return e, bool(got.get("negate"))
    return None, False


def numbers(text):
    """The values on a mod line (ranges in brackets removed), and the first range if the advanced copy shows one."""
    t = _MARKUP.sub(r"\2", text or "")
    rng = _RANGE.search(t)
    vals = [float(n.replace(",", "")) for n in _NUM.findall(_RANGE.sub("", t))]
    return vals, ((float(rng.group(1)), float(rng.group(2))) if rng else None)


def currency(name):
    return load()["currency"].get(name)


# ---------------------------------------------------------------- reading a copied item (any class)
PROP_RE = {
    "quality": re.compile(r"^Quality:\s*\+?(\d+)%"),
    "armour": re.compile(r"^Armour:\s*(\d+)"),
    "evasion": re.compile(r"^Evasion Rating:\s*(\d+)"),
    "energy_shield": re.compile(r"^Energy Shield:\s*(\d+)"),
    "ilvl": re.compile(r"^Item Level:\s*(\d+)"),
    "stack": re.compile(r"^Stack Size:\s*([\d,.\s]+)(?:/\s*([\d,.\s]+))?"),
}
MOD_HEADER = re.compile(r'^\{\s*(?P<kind>[A-Za-z ]+?)\s+Modifier(?:\s+"(?P<name>[^"]*)")?(?:\s*\(Tier:\s*(?P<tier>\d+)\))?')


def read_item(text):
    """Everything the price checker needs from a copied item (Ctrl+C or Ctrl+Alt+C), whatever its class.
    -> dict, or None if the text isn't an item."""
    lines = [l.rstrip() for l in (text or "").replace("\r", "").split("\n")]
    if not lines or not lines[0].startswith("Item Class:"):
        return None
    sections, cur = [], []
    for l in lines:
        if l.startswith("--------"):
            if cur:
                sections.append(cur)
            cur = []
        elif l.strip():
            cur.append(l.strip())
    if cur:
        sections.append(cur)
    head = sections[0]
    cls_text = head[0].split(":", 1)[1].strip()
    rarity = next((l.split(":", 1)[1].strip() for l in head if l.startswith("Rarity:")), "")
    names = [l for l in head[1:] if not l.startswith("Rarity:")]
    item = {"class_text": cls_text, "rarity": rarity, "name": "", "base": None, "group": None, "class": None,
            "defence": None, "quality": 0, "sockets": 0, "socket_types": "", "ilvl": None, "corrupted": False,
            "flags": [], "props": {},
            "stack": None, "mods": [], "unknown": []}
    if rarity in ("Rare", "Unique") and len(names) >= 2:
        item["name"], base_line = names[0], names[1]
    else:
        base_line = names[0] if names else ""
        item["name"] = base_line
    item["base"] = find_base(base_line) or find_base(" ".join(names))
    b = base(item["base"]) if item["base"] else None
    item["class"] = (b or {}).get("class") or class_from_text(cls_text)
    if b:
        item["group"], item["defence"] = b.get("group"), b.get("defence")
    mods_from = None
    for i, sec in enumerate(sections[1:], 1):
        for l in sec:
            for key, rx in PROP_RE.items():
                m = rx.match(l)
                if m:
                    if key == "stack":
                        item["stack"] = int(re.sub(r"[^\d]", "", m.group(1)) or 0)
                        if m.group(2):
                            item["stack_max"] = int(re.sub(r"[^\d]", "", m.group(2)) or 0)
                    else:
                        item["props"][key] = int(m.group(1))
            if l.startswith("Sockets:"):
                letters = re.findall(r"[A-Za-z]", l.split(":", 1)[1])
                item["sockets"], item["socket_types"] = len(letters), "".join(letters).upper()   # S = socket, J = jewel
            if l in FLAG_LINES and FLAG_LINES[l] not in item["flags"]:
                item["flags"].append(FLAG_LINES[l])
            if l.startswith("Item Level:"):
                mods_from = i + 1
    item["corrupted"] = "corrupted" in item["flags"]
    item["quality"] = item["props"].get("quality", 0)
    item["ilvl"] = item["props"].get("ilvl")
    if mods_from is None:
        mods_from = len(sections)
    for sec in sections[mods_from:]:
        kind, tier, mname, source = None, None, None, None
        for l in sec:
            h = MOD_HEADER.match(l)
            if h:                                             # advanced copy: "{ Fractured Suffix Modifier "of X" (Tier: 1) }"
                words = h.group("kind").strip().lower().split()
                source = next((w for w in words if w in SOURCES), None)
                kind = next((w for w in words if w not in SOURCES), None) or "explicit"
                tier = int(h.group("tier")) if h.group("tier") else None
                mname = h.group("name")
                continue
            if l in FLAG_LINES or l.startswith(("Note:", "Place into", "Right click")):
                continue
            tag = _TAGS.search(l)
            tagged = tag.group(1).lower() if tag else None
            k = kind or (tagged if tagged in ("implicit", "rune", "enchant") else "explicit")
            src = source or (tagged if tagged in SOURCES else None)
            stat, neg = stat_for(l)
            vals, rng = numbers(l)
            if neg:
                vals = [-v for v in vals]
            # trade: every id this wording has (any of them matches)
            group_key = src or (k if k in ("implicit", "rune", "enchant") else "explicit")
            m = {"text": l, "kind": k, "source": src, "tier": tier, "affix": mname, "values": vals, "range": rng,
                 "stat": stat["ref"] if stat else None, "local": bool(stat and stat.get("local")),
                 "learned": bool(stat and stat.get("learned")),
                 "trade": list(stat["trade"].get(group_key) or stat["trade"].get("explicit")
                               or next(iter(stat["trade"].values()), [])) if stat else []}
            item["mods"].append(m)
            if not stat:
                item["unknown"].append(l)
    return item
